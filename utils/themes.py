from __future__ import annotations

import re

# Порядок = порядок кнопок в боте. У квиза может быть несколько тем сразу
# ("Кино и музыка" — и в кино, и в музыке), поэтому правила не
# взаимоисключающие. Совпадения ищем по основам слов в нижнем регистре, "ё"
# заменяется на "е".
THEMES: dict[str, re.Pattern[str]] = {
    "Классика / обо всём": re.compile(
        r"классик|классическ|квиз, плиз|\bлайт\b|обо ?всем|логик|школьн|географ"
        r"|литератур|кухн|изи|угадайка обо|телеигр|телеквиз|игра года"
    ),
    "Кино, музыка, сериалы, мультфильмы": re.compile(
        r"кино|фильм|сериал|мульт|медиа|кмс|к\.м\.с|сумерк|аватар|поттер|хогвартс"
        r"|игра престолов|friends|f\.r\.i\.e\.n\.d\.s|сваты|секс в большом|домохозяйк"
        r"|большого взрыва|как я встретил|служебный роман|истори[яи] ужасов"
        r"|человек.?паук|великолепный век|cartoon|disney|nickelodeon|pixar|marvel"
        r"|шрек|shrek|властелин колец|хоббит|one piece|комеди|доктор хаус|анатомия страсти"
        r"|сверхъестествен|шурик"
    ),
    "Музыка": re.compile(
        r"мелоди|музык|музлото|хит|караоке|припев|лото|\bрок\b|rock|рэп|поп-|k-pop"
        r"|mtv|music|тусич|шабаш|попеть|песн|\bмуз\b|зумерск|\bән\b|әнші|танцуем"
    ),
    "Аниме": re.compile(r"аниме|наруто|атака титанов|one piece"),
    "Дорамы": re.compile(r"дорам"),
    "Детективы": re.compile(r"детектив"),
    "Мемы": re.compile(r"мем"),
    "Футбол": re.compile(r"футбол"),
    "18+": re.compile(r"пошл|18\+"),
    "Видеоигры": re.compile(r"видеоигр"),
}

# Организаторы, у которых тема всех игр известна заранее, даже если в
# названии её не видно (Blackbox — "Сезон 4, игра №3"). Пробелы и регистр не важны: источники этих
# организаторов добавляют вручную, и написание может отличаться.
_SOURCE_THEMES: dict[str, set[str]] = {
    "alibi": {"Детективы"},
    "sainttwins": {"Детективы"},
    "detequiz": {"Детективы"},
    "blackbox": {"Классика / обо всём"},
}

OTHER = "Прочее"
ALL_THEMES: list[str] = [*THEMES, OTHER]


def themes_of(title: str, source: str = "") -> set[str]:
    text = title.lower().replace("ё", "е")
    found = {name for name, pattern in THEMES.items() if pattern.search(text)}
    found |= _SOURCE_THEMES.get("".join(source.lower().split()), set())
    return found or {OTHER}
