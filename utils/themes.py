from __future__ import annotations

import re

# Порядок = порядок кнопок в боте. У квиза может быть несколько тем сразу
# ("Музыка и кино СССР" — и музыка, и кино, и эпохи), поэтому правила не
# взаимоисключающие. Совпадения ищем по основам слов в нижнем регистре, "ё"
# заменяется на "е".
THEMES: dict[str, re.Pattern[str]] = {
    "Кино и сериалы": re.compile(
        r"кино|фильм|сериал|мульт|телеквиз|телеигр|медиа|кмс|дорам|сумерк|аватар"
        r"|игра престолов|friends|f\.r\.i\.e\.n\.d\.s|сваты|секс в большом|домохозяйк"
        r"|большого взрыва|как я встретил|служебный роман|истори[яи] ужасов"
        r"|человек.?паук|великолепный век|cartoon|disney|nickelodeon"
    ),
    "Музыка": re.compile(
        r"мелоди|музык|музлото|хит|караоке|припев|лото|\bрок\b|рэп|поп-|k-pop|mtv"
        r"|music|тусич|шабаш|\bмуз\b|зумерск|\bән\b|әнші|танцуем"
    ),
    "Гарри Поттер": re.compile(r"поттер|хогвартс"),
    "Детектив": re.compile(r"детектив"),
    "Аниме и дорамы": re.compile(r"аниме|наруто|атака титанов|дорам"),
    "Видеоигры": re.compile(r"видеоигр"),
    "Мемы и интернет": re.compile(r"мем|интернет"),
    "Эпохи и ретро": re.compile(
        r"(?<!\d)(19|20)\d{2}(?!\d)|(?<!\d)\d0-?е|(?<!\d)\d0х|ссср|советск"
        r"|old school|old vs|эпох|поколение"
    ),
    "Классика и общие знания": re.compile(
        r"классик|классическ|квиз, плиз|\bлайт\b|обо ?всем|логик|школьн|географ"
        r"|литератур|кухн|изи|угадайка обо"
    ),
    "18+": re.compile(r"пошл|18\+"),
    "Хэллоуин": re.compile(r"хэллоуин|ужас"),
}

# Организаторы, у которых любая игра — детектив/расследование, даже если
# в названии этого слова нет. Пробелы и регистр не важны: источники этих
# организаторов добавляют вручную, и написание может отличаться.
_SOURCE_THEMES: dict[str, set[str]] = {
    "alibi": {"Детектив"},
    "sainttwins": {"Детектив"},
    "detequiz": {"Детектив"},
}

OTHER = "Прочее"
ALL_THEMES: list[str] = [*THEMES, OTHER]


def themes_of(title: str, source: str = "") -> set[str]:
    text = title.lower().replace("ё", "е")
    found = {name for name, pattern in THEMES.items() if pattern.search(text)}
    found |= _SOURCE_THEMES.get("".join(source.lower().split()), set())
    return found or {OTHER}
